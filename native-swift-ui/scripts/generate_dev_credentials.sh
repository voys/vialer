#!/bin/sh
# Writes Vialer/Generated/DevCredentials.swift from DEV_USERNAME / DEV_PASSWORD in the repo's .env,
# mirroring the Flutter app's debug-only login pre-fill. Release builds always get nil values.
set -eu

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
ENV_FILE="$ROOT/../.env"
OUT="$ROOT/Vialer/Generated/DevCredentials.swift"
mkdir -p "$(dirname "$OUT")"

value_for() {
    key="$1"
    [ -f "$ENV_FILE" ] || return 0
    grep -E "^${key}=" "$ENV_FILE" | head -1 | cut -d= -f2- | sed 's/^"//; s/"$//'
}

swift_literal() {
    if [ -z "$1" ]; then
        printf 'nil'
    else
        printf '"%s"' "$(printf '%s' "$1" | sed 's/\\/\\\\/g; s/"/\\"/g')"
    fi
}

case "${CONFIGURATION:-Debug}" in Debug*) IS_DEBUG=1;; *) IS_DEBUG=0;; esac
if [ "$IS_DEBUG" = "1" ]; then
    USERNAME="$(value_for DEV_USERNAME)"
    PASSWORD="$(value_for DEV_PASSWORD)"
else
    USERNAME=""
    PASSWORD=""
fi

cat > "$OUT" <<EOF
// Generated by scripts/generate_dev_credentials.sh from ../.env. Gitignored; do not edit.
enum DevCredentials {
    static let username: String? = $(swift_literal "$USERNAME")
    static let password: String? = $(swift_literal "$PASSWORD")
}
EOF
