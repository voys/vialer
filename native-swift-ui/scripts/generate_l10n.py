#!/usr/bin/env python3
"""Generates Vialer/Generated/L10n.swift from the Phrase string catalog.

Keys in Phrase are the Flutter i18n paths, e.g. `onboarding.login.button.signUp(String appName)`.
Each path segment becomes a nested enum; a leaf becomes a static property, or a static function
when the key declares parameters. Values keep Phrase's Dart-style placeholders, which
`L10nFormat` resolves at runtime.

Usage: python3 scripts/generate_l10n.py  (run from native-swift-ui after `phrase pull`)
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
CATALOG = ROOT / "Vialer" / "Resources" / "Localizable.xcstrings"
OUTPUT = ROOT / "Vialer" / "Generated" / "L10n.swift"

SWIFT_KEYWORDS = {
    "as", "break", "case", "catch", "class", "continue", "default", "defer", "do", "else", "enum",
    "extension", "false", "for", "func", "guard", "if", "import", "in", "init", "internal", "is",
    "let", "nil", "operator", "private", "protocol", "public", "repeat", "return", "self", "static",
    "struct", "subscript", "super", "switch", "throw", "throws", "true", "try", "typealias", "var",
    "where", "while", "Type", "description",
}

KEY_RE = re.compile(r"^(?P<path>[^(]+)(?:\((?P<params>.*)\))?$")
TYPE_MAP = {"String": "String", "int": "Int", "double": "Double", "bool": "Bool", "num": "Double"}


def ident(name: str) -> str:
    name = re.sub(r"[^A-Za-z0-9_]", "_", name)
    if name[0].isdigit():
        name = "_" + name
    return f"`{name}`" if name in SWIFT_KEYWORDS else name


class Node:
    def __init__(self):
        self.children = {}
        self.leaves = []  # (name, params, full_key)


def build_tree(keys):
    root = Node()
    for key in keys:
        m = KEY_RE.match(key)
        if not m:
            print(f"skipping unparsable key: {key}", file=sys.stderr)
            continue
        segments = m.group("path").split(".")
        params = []
        if m.group("params"):
            for raw in m.group("params").split(","):
                parts = raw.strip().split()
                if len(parts) != 2:
                    continue
                params.append((parts[1], TYPE_MAP.get(parts[0], "String")))
        node = root
        for segment in segments[:-1]:
            node = node.children.setdefault(segment, Node())
        node.leaves.append((segments[-1], params, key))
    return root


def emit(node: Node, name: str, indent: int, out: list):
    pad = "    " * indent
    out.append(f"{pad}enum {ident(name)} {{")
    leaf_names = {leaf[0] for leaf in node.leaves}
    for leaf_name, params, key in sorted(node.leaves):
        swift_key = key.replace("\\", "\\\\").replace('"', '\\"')
        if params:
            args = ", ".join(f"{ident(p)}: {t}" for p, t in params)
            dict_entries = ", ".join(f'"{p}": {ident(p)}' for p, _ in params)
            out.append(f"{pad}    static func {ident(leaf_name)}({args}) -> String {{")
            out.append(f'{pad}        L10nFormat.resolve("{swift_key}", [{dict_entries}])')
            out.append(f"{pad}    }}")
        else:
            out.append(f'{pad}    static var {ident(leaf_name)}: String {{ L10nFormat.resolve("{swift_key}") }}')
    for child_name in sorted(node.children):
        # A namespace that is also a leaf gets a suffix so both can exist.
        enum_name = child_name + "Section" if child_name in leaf_names else child_name
        emit(node.children[child_name], enum_name, indent + 1, out)
    out.append(f"{pad}}}")


def main():
    catalog = json.loads(CATALOG.read_text())
    keys = sorted(catalog["strings"].keys())
    root = build_tree(keys)
    out = [
        "// Generated by scripts/generate_l10n.py from Vialer/Resources/Localizable.xcstrings.",
        "// Do not edit by hand; run `phrase pull` and regenerate instead.",
        "",
        "import Foundation",
        "",
        "// swiftlint:disable all",
    ]
    emit(root, "L10n", 0, out)
    out.append("")
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(out))
    print(f"wrote {OUTPUT.relative_to(ROOT)} with {len(keys)} keys")


if __name__ == "__main__":
    main()
