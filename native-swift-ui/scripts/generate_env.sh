#!/bin/sh
# Writes Vialer/Generated/Env.swift from the third-party keys in the repo's .env so secrets never
# live in source. Missing keys become nil and the matching integration stays disabled.
set -eu

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
ENV_FILE="$ROOT/../.env"
OUT="$ROOT/Vialer/Generated/Env.swift"
mkdir -p "$(dirname "$OUT")"

value_for() {
    key="$1"
    [ -f "$ENV_FILE" ] || return 0
    grep -E "^${key}=" "$ENV_FILE" | head -1 | cut -d= -f2- | sed 's/^"//; s/"$//'
}

swift_literal() {
    if [ -z "$1" ]; then
        printf 'nil'
    else
        printf '"%s"' "$(printf '%s' "$1" | sed 's/\\/\\\\/g; s/"/\\"/g')"
    fi
}

swift_bool() {
    case "$(printf '%s' "$1" | tr '[:upper:]' '[:lower:]')" in
        1|true) printf 'true';;
        *) printf 'false';;
    esac
}

cat > "$OUT" <<EOF
// Generated by scripts/generate_env.sh from ../.env. Gitignored; do not edit.
enum Env {
    static let sentryDSN: String? = $(swift_literal "$(value_for SENTRY_DSN)")
    static let segmentIOSKey: String? = $(swift_literal "$(value_for SEGMENT_IOS_KEY)")
    static let logentriesIOSToken: String? = $(swift_literal "$(value_for LOGENTRIES_IOS_TOKEN)")
    static let isProduction = $(swift_bool "$(value_for IS_PRODUCTION)")
    static let isMessagingAppsSurveyEnabled = $(swift_bool "$(value_for FEATURE_MESSAGING_APPS_SURVEY)")
}
EOF
